let arr = [1,2,3,4,5];
console.log(arr.length); // printing array length  (length is not a function its a property )

arr.push(10);  // (push)= add element at end of array
console.log(arr);

arr.pop(10);  // (pop)= remove element at end of array
console.log(arr);

arr.shift(); // (shift) = remove first element of array
console.log(arr);

arr.unshift(51);  // (unshift) = add element in front of  array
console.log(arr);

arr.reverse(); // reverse array
console.log(arr);

console.log(arr.indexOf(51));  // return index of element of array


